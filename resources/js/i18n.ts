export function useI18n() {
    const page = usePage();
    const locale = computed<"fr" | "ar">(() =>
        page.props.locale === "ar" ? "ar" : "fr",
    );
    const t = (key: string): string =>
        (messages[locale.value] as Record<string, string>)[key] ?? key;
    return {
        t,
        locale,
        dir: computed(() => (locale.value === "ar" ? "rtl" : "ltr")),
    };
}
